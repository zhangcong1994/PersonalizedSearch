def get_batch_system_prompt(batch: int) -> str:
    """获取指定批次的 system prompt。batch=1 或 batch=2。"""
    if batch == 1:
        return BATCH1_SYSTEM_PROMPT
    elif batch == 2:
        return BATCH2_SYSTEM_PROMPT
    else:
        raise ValueError(f"Invalid batch: {batch}. Use 1 or 2.")


def get_dim_system_prompt(dimension: str, mode: str = "gen_stage") -> str:
    """获取指定维度的独立 system prompt（人机校准用）。"""
    if mode == "gen_stage":
        prompts = GEN_STAGE_DIM_PROMPTS
    elif mode == "system_level":
        prompts = SYSTEM_LEVEL_DIM_PROMPTS
    else:
        raise ValueError(f"Unknown mode: {mode}")

    if dimension not in prompts:
        raise ValueError(
            f"Unknown dimension '{dimension}' for mode '{mode}'. "
            f"Available: {list(prompts.keys())}"
        )
    return prompts[dimension]


def _format_passages(passages: list[dict]) -> str:
    """格式化检索文档列表。"""
    parts = []
    for i, p in enumerate(passages):
        pid = p.get("pid", f"doc-{i}")
        rank = p.get("rank", i + 1)
        text = p.get("text", "")
        text_short = text[:800] + "..." if len(text) > 800 else text
        parts.append(f"[{rank}] pid={pid}")
        parts.append(f"{text_short}\n")
    return "\n".join(parts)


def build_batch_user_message(
    query: str,
    passages: list[dict],
    answer: str,
    batch: int,
) -> str:
    """
    构建批次评分的 user message。

    batch=1: 准确性 + 安全性 + 相关性（所有三个维度都需要 passages）
    batch=2: 整合质量 + 引文质量 + 用户体验（所有三个维度都需要 passages）
    """
    parts = [f"## 用户查询\n\n{query}\n"]

    parts.append("## 检索文档（按精排分数从高到低排列）\n")
    parts.append(_format_passages(passages))

    parts.append(f"## LLM 生成的答案\n\n{answer}\n")

    if batch == 1:
        parts.append("请对以上答案的 **准确性、安全性、相关性** 三个维度进行评分（每个维度 1-4 分整数）。")
    else:
        parts.append("请对以上答案的 **整合质量、引文质量、用户体验** 三个维度进行评分（每个维度 1-4 分整数）。")

    return "\n".join(parts)


def build_dim_user_message(
    query: str,
    passages: list[dict],
    answer: str,
    dimension: str,
    system_prompt_text: str = None,
) -> str:
    """
    构建逐维度评分的 user message（人机校准用）。

    根据维度智能选择需要包含的信息：
    - safety, relevance, self_consistency, answer_structuring 不需要 passages
    - instruction_following 必须包含 system_prompt_text
    """
    parts = [f"## 用户查询\n\n{query}\n"]

    dims_no_passages = {"safety", "relevance", "user_experience", "answer_structuring", "self_consistency"}
    if dimension not in dims_no_passages:
        parts.append("## 检索文档（按精排分数从高到低排列）\n")
        parts.append(_format_passages(passages))

    if system_prompt_text and dimension in ("instruction_following",):
        parts.append(f"## LLM 的 System Prompt\n\n```\n{system_prompt_text}\n```\n")

    parts.append(f"## LLM 生成的答案\n\n{answer}\n")

    dim_label = GEN_STAGE_DIM_LABELS.get(dimension, dimension)
    parts.append(f"请对以上答案的 **{dim_label}** 维度进行评分（1-4 分整数）。")

    return "\n".join(parts)


def build_gen_stage_judge_input(
    query: str,
    passages: list[dict],
    answer: str,
    system_prompt_text: str = None,
    dimension: str = None,
    batch: int = None,
) -> str:
    """
    构建 Judge 的完整 user message。

    优先级：
    1. batch 指定 → 返回批次评估的 user message
    2. dimension 指定 → 返回该维度的 user message（人机校准用）
    3. 都不指定 → 返回通用 message（兼容旧接口，包含所有信息）
    """
    if batch is not None:
        return build_batch_user_message(query, passages, answer, batch)
    if dimension:
        return build_dim_user_message(query, passages, answer, dimension, system_prompt_text)

    parts = [f"## 用户查询\n\n{query}\n"]
    parts.append("## 检索文档（按精排分数从高到低排列）\n")
    parts.append(_format_passages(passages))
    if system_prompt_text:
        parts.append(f"## LLM 的 System Prompt\n\n```\n{system_prompt_text}\n```\n")
    parts.append(f"## LLM 生成的答案\n\n{answer}\n")
    return "\n".join(parts)


def build_system_level_judge_input(
    query: str,
    passages: list[dict],
    answer: str,
    dimension: str = None,
) -> str:
    """构建系统级 Judge 的 user message。"""
    return build_gen_stage_judge_input(query, passages, answer, dimension=dimension)


def parse_judge_response(response_text: str) -> dict | None:
    """
    解析 Judge LLM 返回的 JSON。

    返回 dict 或 None（解析失败时）。
    """
    text = response_text.strip()

    if text.startswith("```json"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
    text = text.strip()

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return None


