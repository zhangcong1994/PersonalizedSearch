# ===========================================================================
# Prompt 管理器
# ===========================================================================

class PromptV2Manager:
    """支持版本切换的 Prompt 管理器。接口与原 PromptManager 一致。"""

    PROMPTS = {
        "v0": PROMPT_V0_SYSTEM,
        "v1-full": PROMPT_V1_FULL_SYSTEM,
        "v2": PROMPT_V2_SYSTEM,
        "v2-rules-only": PROMPT_V2_RULES_ONLY,
        "v2-contrast-only": PROMPT_V2_CONTRAST_ONLY,
        "v3": PROMPT_V3_SYSTEM,
        "abl-no-contrast": PROMPT_ABL_NO_CONTRAST,
        "abl-no-rules": PROMPT_ABL_NO_RULES,
        "abl-no-cot": PROMPT_ABL_NO_COT,
        "abl-no-refusal": PROMPT_ABL_NO_REFUSAL,
    }

    def __init__(self, version: str = "v0"):
        if version not in self.PROMPTS:
            raise ValueError(
                f"Unknown prompt version: {version}. "
                f"Available: {list(self.PROMPTS.keys())}"
            )
        self.version = version
        self.user_template = USER_PROMPT_TEMPLATE

    def get_system_prompt(self, query_type: str = "default") -> str:
        return self.PROMPTS[self.version]

    def build_user_prompt(self, question: str, context: str) -> str:
        return self.user_template.format(context=context, question=question)


# ===========================================================================
# 便捷函数
# ===========================================================================

def list_versions() -> list[str]:
    """列出所有可用的 prompt 版本。"""
    return list(PromptV2Manager.PROMPTS.keys())


def get_prompt_manager(version: str = "v0") -> PromptV2Manager:
    return PromptV2Manager(version=version)
